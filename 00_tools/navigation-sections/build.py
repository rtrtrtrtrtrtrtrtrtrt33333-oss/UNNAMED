"""Rebuild navigation list bundles after editing the original list HTML files."""
from pathlib import Path
import json
import os
import re
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[2]
PROJECTS = ['02_Unnamed project', '02_Guts and Blackpowder', '02_unsorted ocs']


def rebase(text, source, destination):
    def replace(match):
        prefix, value, quote = match.groups()
        if value.startswith(('#', 'http:', 'https:', 'data:', '/')):
            return match[0]
        path, *fragment = value.split('#', 1)
        target = source.parent / unquote(path)
        relative = os.path.relpath(target, destination.parent).replace('\\', '/')
        return prefix + relative + ('#' + fragment[0] if fragment else '') + quote
    return re.sub(r'((?:href|src)=["\'])([^"\']+)(["\'])', replace, text)


def sources(nav):
    result = {}
    for name in ['characters', 'regions', 'empires', 'timelines', 'aspects']:
        candidates = [nav / f'{name}-list/{name[:-1]}-list-page.html', nav / f'lists/{name}/index.html']
        for candidate in candidates:
            if candidate.exists():
                result[name] = candidate
                break
    return result


def build():
    for project in PROJECTS:
        nav = ROOT / project / 'Navigation'
        home = nav / 'home/index.html'
        bundle = {}
        for name, page in sources(nav).items():
            text = page.read_text(encoding='utf-8-sig')
            main = re.search(r'<main\b[^>]*>([\s\S]*?)</main>', text)
            if not main:
                raise ValueError(f'No main in {page}')
            bundle[name] = rebase(main[1], page, home)
        (nav / '00_code/sections-data.js').write_text(
            '/* Generated by 00_tools/navigation-sections/build.py */\nwindow.navigationSections = '
            + json.dumps(bundle, ensure_ascii=False) + ';\n', encoding='utf-8')
        print(f'{project}: {len(bundle)} sections')


if __name__ == '__main__':
    build()
